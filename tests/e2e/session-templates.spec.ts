import { resolve } from 'node:path'
import { expect, test } from '@playwright/test'
import { createE2EServer, finishE2EServer } from '../support/e2e-server.ts'

test('P4-01 a P4-08: copia Markdown no rascunho e confirma antes de substituir texto', async ({ page, request }) => {
  const app = createE2EServer(':memory:', resolve('dist'))
  try {
    const origin = await app.listen({ host: '127.0.0.1', port: 0 })
    const { id } = await (await request.post(origin + '/api/campaigns', { data: { name: 'Farol' } })).json()
    const sessions = origin + '/api/campaigns/' + id + '/sessions'
    await page.goto(origin)
    await page.getByRole('button', { name: 'Farol', exact: true }).click()
    const newSession = page.getByRole('button', { name: 'Nova sessão', exact: true })
    await newSession.click()
    const notes = page.getByLabel('Anotações', { exact: true })
    await page.getByText('Dados da sessão', { exact: true }).click()
    const title = page.getByLabel('Título', { exact: true })
    const model = page.getByLabel('Modelo de sessão')
    const apply = page.getByRole('button', { name: 'Aplicar modelo' })
    const preview = page.getByRole('region', { name: 'Prévia Markdown' })
    await expect(notes).toHaveValue('')
    await expect(model).toBeVisible({ timeout: 4000 })
    await title.fill('Chegada ao farol')
    await model.selectOption('narrative')
    await apply.click()
    await expect(title).toHaveValue('Chegada ao farol')
    await expect(preview.getByRole('heading', { name: 'Resumo' })).toBeVisible()
    const narrative = await notes.inputValue()
    await model.selectOption('free')
    page.once('dialog', (dialog) => void dialog.dismiss())
    await apply.click()
    await expect(notes).toHaveValue(narrative)
    await model.selectOption('investigation')
    page.once('dialog', (dialog) => void dialog.dismiss())
    await apply.click()
    await expect(notes).toHaveValue(narrative)
    page.once('dialog', (dialog) => void dialog.accept())
    await apply.click()
    await expect(preview.getByRole('heading', { name: 'Pistas encontradas' })).toBeVisible()
    const edited = await notes.inputValue() + '\nMapa encontrado na biblioteca.'
    await notes.fill(edited)
    await expect(page.getByRole('status')).toContainText('rascunho protegido')
    expect(await (await request.get(sessions)).json()).toEqual([])
    await page.getByRole('button', { name: 'Salvar', exact: true }).click()
    await expect(page.getByRole('status')).toHaveText('Salvo no servidor')
    await expect(model).toHaveCount(0)
    await page.getByRole('button', { name: 'Voltar à campanha' }).click()
    await newSession.click()
    await expect(notes).toHaveValue('')
    await model.selectOption('narrative')
    await apply.click()
    await page.getByRole('button', { name: 'Voltar à campanha' }).click()
    await page.getByRole('button', { name: 'Continuar mantendo o rascunho' }).click()
    await page.getByRole('button', { name: 'Chegada ao farol', exact: true }).click()
    await expect(notes).toHaveValue(edited)
    await expect(model).toHaveCount(0)
  } finally { await finishE2EServer(app, [page.context()], request) }
})
